const validLanguages = new Set(['en', 'fi']);
let language = 'en';

export function getLanguage() {
  return language;
}

export function formatNumber(value, options) {
  return Number(value).toLocaleString(language === 'fi' ? 'fi-FI' : 'en-US', options);
}

export function t(key, params = {}) {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  return template.replace(/\{([\w]+)\}/g, (_, name) => {
    const value = params[name];
    if (value && typeof value === 'object' && value.key) return t(value.key, value.params);
    return String(value ?? `{${name}}`);
  });
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(element => {
    element.title = t(element.dataset.i18nTitle);
  });
  document.documentElement.lang = language;
  document.title = t('document.title');
  const languageCode = document.querySelector('#language-code');
  if (languageCode) languageCode.textContent = language.toUpperCase() + ' / 01';
}

export function setLanguage(nextLanguage) {
  if (!validLanguages.has(nextLanguage)) return;
  language = nextLanguage;
  try { localStorage.setItem('ilmatila-language', language); } catch {}
  applyTranslations();
  document.dispatchEvent(new CustomEvent('ilmatila:languagechange', { detail: { language } }));
}

export function initializeLanguagePicker() {
  let saved = 'en';
  try {
    const stored = localStorage.getItem('ilmatila-language');
    if (validLanguages.has(stored)) saved = stored;
  } catch {}
  language = saved;
  const picker = document.querySelector('#language-select');
  if (picker) {
    picker.value = language;
    picker.addEventListener('change', () => setLanguage(picker.value));
  }
  applyTranslations();
}
